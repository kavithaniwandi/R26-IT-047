"""Generate v3 records exclusively from its manifest and metrics."""
from __future__ import annotations

import json
from pathlib import Path


def main() -> None:
    base = Path(__file__).resolve().parent.parent
    model_dir = base / "v3_retrained"
    manifest = json.loads((model_dir / "manifest.json").read_text(encoding="utf-8"))
    metrics = json.loads((model_dir / "metrics.json").read_text(encoding="utf-8"))
    for field in ("test_accuracy", "selected_boundary_tolerance"):
        if manifest[field] != metrics[field]:
            raise ValueError(f"Manifest/metrics disagree on {field}")
    tolerance = metrics["selected_boundary_tolerance"]

    def pct(value):
        return f"{value * 100:.4f}%"

    lines = [
        "# Donation Appeal quality v3 model card",
        "",
        "Generated by training/generate_metadata.py from v3_retrained/manifest.json",
        "and v3_retrained/metrics.json. Do not hand-edit reported numbers.",
        "",
        "## Identity and deployment",
        "",
        "- Default directory: backend/ml_models/Donation Appeal/v3_retrained",
        "- APPEAL_MODEL_DIR remains an explicit override.",
        f"- Export created (UTC): {manifest['created_utc']}",
        "- Pre-v3 model sets were removed on purpose.",
        "",
        "## Dataset and evaluation protocol",
        "",
        f"- Dataset: {manifest['data_file']}",
        f"- Dataset SHA-256: {manifest['data_sha256']}",
        f"- Development rows: {manifest['development_rows']}",
        f"- Held-out rows: {manifest['test_rows']}",
        "",
        "Load/cleaning counts:",
        "",
        "| Stage | Rows |",
        "|---|---:|",
    ]
    lines += [f"| {key} | {value} |" for key, value in manifest["load_info"].items()]
    lines += ["", "Protocol recorded by the export:", "", "| Setting | Value |", "|---|---|"]
    lines += [f"| {key} | {value} |" for key, value in manifest["protocol"].items()]
    lines += [
        "",
        "## Label, displayed score, and confidence",
        "",
        "The runtime label is the classifier's highest-probability category, independent",
        "of the numerical regression score. A score of 3.79 can therefore have a Medium",
        "label. The exported hybrid boundary tolerance is retained as training metadata",
        "but no longer controls runtime labels.",
        "",
        "quality_score is the post-isotonic score bounded to [1.00, 5.00], rounded to",
        "two decimals. It is not clipped to the final label's band, so improvements",
        "within a category remain visible. raw_quality_score retains the same value",
        "for API compatibility. Model probabilities and numerical predictions are unchanged.",
        "Confidence is the classifier probability of the final label, rounded to three decimals,",
        "and flags low confidence below 0.50.",
        "",
        "## Held-out results",
        "",
        "The final-label results below were exported under the original hybrid policy.",
        "The classifier-only accuracy row applies to the current runtime label policy.",
        "The exported confusion matrix and per-language results remain historical.",
        "",
        "| Measure | Value |",
        "|---|---:|",
        f"| Final-label accuracy | {pct(metrics['test_accuracy'])} |",
        f"| Correct / total | {metrics['test_rows_correct']} / {metrics['test_rows']} |",
        f"| Macro-F1 | {metrics['test_macro_f1']:.6f} |",
        f"| Classifier-only accuracy | {pct(metrics['test_classifier_only_accuracy'])} |",
        f"| Score-band-only accuracy | {pct(metrics['test_score_band_only_accuracy'])} |",
        f"| Majority-class baseline | {pct(metrics['majority_class_baseline'])} |",
        f"| Unclamped label/score-band agreement | {pct(metrics['test_label_matches_score_band'])} |",
        f"| Unclamped score MAE | {metrics['test_score_mae']:.6f} |",
        f"| Unclamped score R2 | {metrics['test_score_r2']:.6f} |",
        "",
        "MAE and R2 refer to the original post-isotonic model scores. The API displays",
        "these scores rounded to two decimals, without clipping them to label bands.",
        "",
        "## Per-language results",
        "",
        "| Language | Held-out rows | Accuracy |",
        "|---|---:|---:|",
    ]
    lines += [
        f"| {language} | {result['n']} | {pct(result['accuracy'])} |"
        for language, result in metrics["per_language"].items()
    ]
    labels = metrics["confusion_matrix_labels"]
    lines += [
        "",
        "## Confusion matrix and per-class results",
        "",
        "Rows are true labels; columns are final predicted labels.",
        "Label order: " + ", ".join(labels) + ".",
        "",
        "| True / predicted | " + " | ".join(labels) + " |",
        "|---|" + "---:|" * len(labels),
    ]
    lines += [
        "| " + label + " | " + " | ".join(str(x) for x in row) + " |"
        for label, row in zip(labels, metrics["confusion_matrix"])
    ]
    lines += ["", "| Class | Precision | Recall | F1 | Support |", "|---|---:|---:|---:|---:|"]
    lines += [
        f"| {label} | {values['precision']:.6f} | {values['recall']:.6f} | "
        f"{values['f1-score']:.6f} | {values['support']:g} |"
        for label, values in metrics["per_class"].items()
    ]
    lines += [
        "",
        "## Development cross-validation and tolerance selection",
        "",
        f"- CV accuracy mean: {metrics['cv_accuracy_mean']:.6f}",
        f"- CV accuracy standard deviation: {metrics['cv_accuracy_std']:.6f}",
        "- CV fold accuracies: " + ", ".join(f"{x:.6f}" for x in metrics["cv_fold_accuracy"]),
        "- Classifier-only CV fold accuracies: "
        + ", ".join(f"{x:.6f}" for x in metrics["cv_classifier_only_fold_accuracy"]),
        "",
        "| Candidate tolerance | Recorded accuracy |",
        "|---:|---:|",
    ]
    lines += [f"| {t} | {accuracy:.6f} |" for t, accuracy in metrics["tolerance_sweep"].items()]
    lines += ["", "## Export environment", "", "| Package | Version |", "|---|---|"]
    lines += [f"| {key} | {value} |" for key, value in manifest["environment"].items()]
    lines += ["", "## Artifact integrity", "", "| File | SHA-256 |", "|---|---|"]
    lines += [f"| {name} | {digest} |" for name, digest in manifest["artifacts"].items()]
    language_results = metrics["per_language"]
    english_lower = all(
        language_results["English"]["accuracy"] < language_results[language]["accuracy"]
        for language in ("Sinhala", "Tamil")
    )
    regressor_lower = (
        metrics["test_score_band_only_accuracy"] < metrics["test_classifier_only_accuracy"]
    )
    lines += [
        "",
        "## Limitations",
        "",
        ("- English accuracy is lower than Sinhala and Tamil."
         if english_lower else "- Language accuracy ordering differs; inspect the table above."),
        ("- The regressor-based score-band rule alone is substantially less accurate than "
         "the classifier-only rule; its continuous scores should not be treated as class confidence."
         if regressor_lower else "- Inspect classifier-only and score-band-only results separately."),
        "- No held-out source-row IDs or appeal texts were saved in the export. "
        "test_predictions.csv supports checking reported predictions, but not independent "
        "re-scoring or exact source-row reconstruction.",
        "- Dataset provenance and protocol are statements recorded in the supplied manifest; "
        "the export contains no training-source hash.",
        "- Published regression metrics and displayed scores both use the post-isotonic "
        "score without clipping it to a label band.",
        "",
    ]
    card = "\n".join(lines)
    evaluation = {
        "model_directory": "v3_retrained",
        "source_files": ["v3_retrained/manifest.json", "v3_retrained/metrics.json"],
        "manifest": manifest,
        "metrics": metrics,
    }
    # Validate and render everything before replacing either generated record.
    evaluation_text = json.dumps(evaluation, indent=2, ensure_ascii=False) + "\n"
    (base / "APPEAL_MODEL_CARD.md").write_text(card, encoding="utf-8")
    (base / "appeal_eval.json").write_text(evaluation_text, encoding="utf-8")
    print(card)


if __name__ == "__main__":
    main()
